"""Emit README.md: the customer-facing document for the generated project.

The README is generated from the same data that generates the Terraform, so it
cannot drift from the code. In particular the Secrets table is built from the
SecretSpec list the secret binder produced — the keys listed are exactly the keys
modules/secrets.tf checks for.
"""
from __future__ import annotations

import json
from pathlib import Path

from .model import SecretSpec, Tenant


def _secrets_section(secrets: list[SecretSpec], review_notes: list[str]) -> list[str]:
    out = [
        "## Secrets", "",
        "Auth0 never returns secret values, so none are stored in this repository. "
        "You provide them to Terraform through **one variable, `secrets`**: a flat map "
        "of `key -> value` strings.", "",
        "**Binding the values is your responsibility.** This project does not read from "
        "any vault or CI system. Build the map from whatever store you use and hand it to "
        "Terraform in either of these ways:", "",
        "| Method | How |",
        "|---|---|",
        "| File | Save the template below as `envs/<env>/secrets.auto.tfvars.json`. "
        "Terraform loads it automatically. It is ignored by `.gitignore`; never commit it. |",
        "| Environment variable | `export TF_VAR_secrets='{...}'`, where `{...}` is the object "
        "inside `\"secrets\"` in the template, as one line of JSON. |", "",
        "Rules:", "",
        "- Keys are **case sensitive** and must match exactly.",
        "- **Every key in the table is required.** `terraform plan` fails with one "
        "message listing any that are missing.",
        "- Values are written to the Terraform state. Use an encrypted, access-controlled "
        "state backend.",
        "- Secrets Auth0 generates itself (application client secrets, signing keys) are "
        "not in this list; they are created on apply and kept in state.", "",
    ]
    if not secrets:
        out += ["**This tenant needs no customer-supplied secrets.**", ""]
    else:
        out += [f"### Required keys ({len(secrets)})", "",
                "| Key | Used by | Purpose |", "|---|---|---|"]
        for s in secrets:
            out.append(f"| `{s.key}` | `{s.tf_type}` `{s.resource}` | {s.purpose} |")

        template = {"secrets": {s.key: s.hint for s in secrets}}
        out += ["", "### Template", "",
                f"This file lists **all {len(secrets)} keys**. Replace every `<value>` with the "
                "real value; do not delete any line, or `terraform plan` will report the "
                "key as missing.", "",
                "```json", json.dumps(template, indent=2), "```", ""]
        if any(s.hint != "<value>" for s in secrets):
            out += ["A value written as `{\"<field>\": \"<value>\"}` is itself a JSON object, "
                    "stored as a string. In the file, escape its quotes (`\\\"`) or build the "
                    "file with a tool that does it for you.", ""]
    if review_notes:
        out += ["### Sensitive settings not handled automatically", "",
                "The Auth0 provider accepts secrets on these settings, but the export "
                "cannot show whether the source tenant uses them (Auth0 returns `null`). "
                "If you use them, add the values by hand:", ""]
        out += [f"- {n}" for n in review_notes]
        out += [""]
    return out


def _env_specific_section(tenant: Tenant | None) -> list[str]:
    out = ["## Values that differ per environment", "",
           "The exported values describe the source tenant. Review these before applying "
           "to another tenant:", ""]
    items: list[str] = []
    if tenant is not None:
        for r in tenant.of_type("auth0_custom_domain"):
            items.append(f"`custom_domains.{r.key}`: the domain `{r.attrs.get('domain')}` "
                         "belongs to the source tenant. Use the target tenant's domain and "
                         "complete DNS verification.")
        for r in tenant.of_type("auth0_action"):
            ids = [n for n in r.attrs.get("secret_names", [])
                   if n.upper().endswith(("_ID", "_IDS", "_NAME", "_NAMES"))]
            if ids:
                items.append(f"`actions.{r.key}`: {', '.join(f'`{n}`' for n in ids)} hold "
                             "application, role or form identifiers. They are listed under "
                             "Secrets; supply the values from the target tenant.")
    items.append("Client IDs, role IDs and other identifiers are generated by Auth0 when "
                 "resources are created; they will differ in every tenant.")
    out += [f"- {i}" for i in items]
    return out + [""]


def emit_readme(out_dir: Path, counts: dict[str, int], envs: list[str],
                unresolved: list[str],
                generic_types: list[str] | None = None,
                excluded: list[str] | None = None,
                secrets: list[SecretSpec] | None = None,
                review_notes: list[str] | None = None,
                tenant: Tenant | None = None,
                active_env: str | None = None,
                provider_version: str | None = None) -> None:
    out_dir = Path(out_dir)
    secrets = secrets or []
    active = active_env or (envs[0] if envs else "<env>")
    total = sum(counts.values())

    lines = [
        "# Auth0 Terraform Project", "",
        "Terraform configuration that recreates an Auth0 tenant, generated by the "
        "`auth0-terraform` skill from a live tenant export.", "",
        "You own this project from here: wiring secrets, choosing a state backend and "
        "running `terraform` in your own pipeline are all up to you. "
        "This README tells you what is needed.", "",
        "## Contents", "",
        "- [Layout](#layout)",
        "- [Prerequisites](#prerequisites)",
        "- [Getting started](#getting-started)",
        "- [Secrets](#secrets)",
        "- [Values that differ per environment](#values-that-differ-per-environment)",
        "- [Imported resources](#imported-resources)", "",
        "## Layout", "",
        "```text",
        "modules/                 shared definition of the tenant (one file per resource type)",
        "  secrets.tf             the `secrets` variable and the required-keys check",
        "  code/                  extracted action code, email templates, login page",
        "envs/",
    ]
    for e in envs:
        marker = "populated from the exported tenant" if e == active else "empty skeleton"
        lines.append(f"  {e + '/':<22} {marker}")
    lines += [
        "```", "",
        "Each `envs/<env>/` directory is a Terraform root: `main.tf` calls the shared "
        "module, `terraform.tfvars` holds that environment's non-secret values, and "
        "`backend.tf` is where you configure state storage.", "",
        "## Prerequisites", "",
        "- **Terraform 1.11 or later.** The Auth0 provider uses write-only attributes, which "
        "older versions reject.",
        f"- **Auth0 provider `{provider_version or 'see modules/versions.tf'}`**, pinned in "
        "`modules/versions.tf` and installed by `terraform init`.",
        "- **A Machine-to-Machine application in the target tenant**, authorised on the "
        "*Auth0 Management API* with permission to manage the resources in this project. "
        "Pass its credentials as `auth0_domain`, `auth0_client_id` and `auth0_client_secret`.",
        "- **A remote state backend** (recommended). See `envs/<env>/backend.tf`.", "",
        "## Getting started", "",
        "```bash",
        f"cd envs/{active}",
        "# 1. configure the backend in backend.tf, then:",
        "terraform init",
        "# 2. provide the provider credentials and the secrets (see Secrets below)",
        "export TF_VAR_auth0_domain=<tenant>.<region>.auth0.com",
        "export TF_VAR_auth0_client_id=<m2m client id>",
        "export TF_VAR_auth0_client_secret=<m2m client secret>",
        "export TF_VAR_secrets='{...}'",
        "# 3. review, then apply",
        "terraform plan",
        "terraform apply",
        "```", "",
        "The first `plan` against an empty tenant shows every resource as an addition. "
        "To populate another environment, copy `envs/" + active + "/terraform.tfvars` into it, "
        "adjust the values for that tenant, and copy `main.tf`, `variables.tf`, "
        "`providers.tf` and `secrets.tf`.", "",
    ]
    lines += _secrets_section(secrets, review_notes or [])
    lines += _env_specific_section(tenant)

    lines += [f"## Imported resources", "", f"{total} resources across {len(counts)} types.", "",
              "| Resource type | Count |", "|---|---|"]
    for tf_type, n in sorted(counts.items()):
        lines.append(f"| `{tf_type}` | {n} |")
    lines.append("")

    if excluded:
        lines += ["### Excluded: created automatically by Auth0", "",
                  "Every Auth0 tenant provisions these itself, so they are intentionally not "
                  "replicated (managing them would be redundant and conflict with the "
                  "tenant's built-ins):", ""]
        lines += [f"- {e}" for e in excluded]
        lines.append("")
    if generic_types:
        lines += ["### Review: generically handled types", "",
                  "These types have no hand-tuned mapping. Check the generated `.tf` file, "
                  "variable schema and tfvars for sensible naming and structure:", ""]
        lines += [f"- `{t}`" for t in sorted(generic_types)]
        lines.append("")
    if unresolved:
        lines += ["### Review: unresolved references", "",
                  "These source-tenant IDs could not be replaced with Terraform references:", ""]
        lines += [f"- `{u}`" for u in unresolved]
        lines.append("")
    (out_dir / "README.md").write_text("\n".join(lines).rstrip() + "\n")
